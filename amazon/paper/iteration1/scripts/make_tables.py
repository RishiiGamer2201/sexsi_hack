for mut in sorted(FAM, key=lambda m: (FAM[m], -e0[("R_exec_rex", "mutant:" + m)]["rate"])):
    k = "mutant:" + mut
    ta.append(f"\\texttt{{{mut.replace('_', chr(92) + '_')}}} & {FAM[mut]} & {e0[('R_exec_rex', k)]['n']} & "
              f"{pct(e0[('R_exec_set', k)]['rate'])} & {pct(e0[('R_exec_rex', k)]['rate'])} & "
              f"{pct(e0[('R_cf_strict@random', k)]['rate'])} \\\\")
