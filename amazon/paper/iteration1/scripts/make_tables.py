for name, s in sorted(a2.items(), key=lambda kv: -kv[1]["lucky_share_of_EX_ci95"][0]):
    tb.append(f"{name} & {pct(s['EX'])} & {pct(s['TS'])} & {s['lucky']}/{s['EX_pass']} & {ci(s['lucky_share_of_EX_ci95'])} \\\\")
