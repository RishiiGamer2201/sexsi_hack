# ---------------------------------------------------------------- Appendix: training seeds
se, sp = load("seeds_eval.json"), load("e13_spider_ours.json")["comparisons"]
dci = lambda v: f"${100 * v[0]:+.1f}${{\\,[${100 * v[1]:+.1f}$, ${100 * v[2]:+.1f}$]}}".replace("$-0.0$", "$0.0$")
d = lambda r: dci(r["diff_bootstrap95"])
tc = [
    "% generated by scripts/make_tables.py -- src: results/seeds_eval.json, results/e13_spider_ours.json",
    "\\begin{tabular}{lrrrrrr}", "\\toprule",
    "Seed & B & C & C$-$B & B$-$SFT & C$-$SFT & Spider C$-$B \\\\", "\\midrule",
]
for s, k in zip(sorted(se["seeds"]), ["C_vs_B", "C_s1_vs_B_s1", "C_s2_vs_B_s2"]):
    r = se["seeds"][s]
    tc.append(f"{s} & {pct(r['B']['verified'][0])} & {pct(r['C']['verified'][0])} & {d(r['C_minus_B'])} & {d(r['B_minus_SFT'])}"
              f" & {d(r['C_minus_SFT'])} & {dci(sp[k]['TS_diff_bootstrap95'])} \\\\")
po, sl = se["pooled"], se["seed_level"]
tc.append(f"Pooled & {pct(po['B_verified'])} & {pct(po['C_verified'])} & {d(po['C_minus_B'])} & {d(po['B_minus_SFT'])}"
          f" & {d(po['C_minus_SFT'])} & {dci(sp['C_pool_vs_B_pool']['TS_diff_bootstrap95'])} \\\\")
t = lambda v: dci([v["mean"], *v["t95"]])
tc.append(f"Seed level & & & {t(sl['C_minus_B'])} & {t(sl['B_minus_SFT'])} & {t(sl['C_minus_SFT'])} & {t(sl['spider_TS_C_minus_B'])} \\\\")
tc += ["\\bottomrule", "\\end{tabular}"]
(OUT / "tableA_seeds.tex").write_text("\n".join(tc) + "\n")
print("wrote tables to", OUT)
