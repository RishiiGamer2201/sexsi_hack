"""Cover GIF for the HF Daily Papers entry of arXiv 2611.34363.

Usage: python make_cover_gif.py OUT.gif [PREVIEW_DIR]
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

W, H = 1200, 675
FD = "/usr/share/fonts/truetype/dejavu/"
BG, INK, MUTED, LINE = "#ffffff", "#16192b", "#6b7280", "#d7dbe3"
GREEN, RED, BLUE, GREY, HL = "#1b9e5a", "#d1373f", "#3b5bdb", "#b8bec9", "#fff3bf"


def font(size, bold=False, mono=False):
    name = ("DejaVuSansMono" if mono else "DejaVuSans") + ("-Bold" if bold else "") + ".ttf"
    return ImageFont.truetype(FD + name, size)


def canvas():
    im = Image.new("RGB", (W, H), BG)
    return im, ImageDraw.Draw(im)


def footer(d):
    d.text((W // 2, H - 28), "arXiv 2611.34363  ·  counterfactual-sql", font=font(18), fill=MUTED, anchor="mm")


def table(d, x, y, rows, hl=(), w=300, title=None):
    if title:
        d.text((x, y - 34), title, font=font(20, bold=True), fill=INK)
    rh = 36
    d.rectangle([x, y, x + w, y + rh], fill="#eef1f6")
    d.text((x + 14, y + rh // 2), "name", font=font(18, bold=True), fill=INK, anchor="lm")
    d.text((x + w // 2 + 10, y + rh // 2), "city", font=font(18, bold=True), fill=INK, anchor="lm")
    for i, (n, c) in enumerate(rows):
        ty = y + rh * (i + 1)
        if i in hl:
            d.rectangle([x, ty, x + w, ty + rh], fill=HL)
        d.text((x + 14, ty + rh // 2), n, font=font(18), fill=INK, anchor="lm")
        d.text((x + w // 2 + 10, ty + rh // 2), c, font=font(18), fill=INK, anchor="lm")
    d.rectangle([x, y, x + w, y + rh * (len(rows) + 1)], outline=LINE, width=2)
    return y + rh * (len(rows) + 1)


def code(d, x, y, s, w, color=INK):
    d.rounded_rectangle([x, y, x + w, y + 52], radius=8, fill="#f5f6f8", outline=LINE, width=2)
    d.text((x + 16, y + 26), s, font=font(21, mono=True), fill=color, anchor="lm")


Q = "Q: How many customers live in Delhi?"
BUGGY = "SELECT COUNT(*) FROM customers;"
DB = [("Asha", "Delhi"), ("Ravi", "Delhi"), ("Meera", "Delhi")]


def title_card():
    im, d = canvas()
    d.text((W // 2, 230), "Single-Database Rewards", font=font(58, bold=True), fill=INK, anchor="mm")
    d.text((W // 2, 300), "Are Hackable", font=font(58, bold=True), fill=RED, anchor="mm")
    d.text((W // 2, 385), "Counterfactual Execution for Trustworthy Text-to-SQL RL", font=font(28), fill=INK, anchor="mm")
    d.text((W // 2, 450), "Shreshth Rai  ·  Rishii Kumar Singh  ·  Aksh Aggarwal", font=font(22), fill=MUTED, anchor="mm")
    d.text((W // 2, 485), "AIMS-DTU, Delhi Technological University", font=font(20), fill=MUTED, anchor="mm")
    footer(d)
    return im


def single_db(step):
    im, d = canvas()
    d.text((60, 50), "The usual reward: compare results on ONE database", font=font(30, bold=True), fill=INK)
    d.text((60, 120), Q, font=font(24), fill=INK)
    d.text((60, 180), "Agent's query (bug: no WHERE city = 'Delhi')", font=font(18), fill=MUTED)
    code(d, 60, 208, BUGGY, 560, RED)
    table(d, 760, 170, DB, title="Training database")
    if step >= 1:
        d.text((60, 320), "Reference answer:", font=font(26), fill=INK)
        d.text((330, 320), "3", font=font(26, bold=True), fill=INK)
    if step >= 2:
        d.text((60, 370), "Agent's answer:", font=font(26), fill=INK)
        d.text((330, 370), "3", font=font(26, bold=True), fill=INK)
    if step >= 3:
        d.rounded_rectangle([60, 440, 620, 520], radius=12, fill="#e7f6ee", outline=GREEN, width=3)
        d.text((340, 480), "✓  Reward 1.0: paid in full", font=font(30, bold=True), fill=GREEN, anchor="mm")
        d.text((W // 2, 590), "Every customer here happens to live in Delhi, so the wrong query matches by luck.",
               font=font(22), fill=INK, anchor="mm")
    footer(d)
    return im


COPIES = [
    ("Copy 1", DB + [("Kabir", "Mumbai")], {3}, 3, 4),
    ("Copy 2", [("Asha", "Delhi"), ("Ravi", "Pune"), ("Meera", "Delhi")], {1}, 2, 3),
    ("Copy 3", DB + [("Tara", "Delhi")], {3}, 4, 4),
]


def counterfactual(step):
    im, d = canvas()
    d.text((60, 40), "Counterfactual reward: also run it on hidden copies", font=font(30, bold=True), fill=INK)
    code(d, 60, 95, BUGGY, 560, RED)
    d.text((650, 121), "copies are generated by code", font=font(18), fill=MUTED, anchor="lm")
    for i, (name, rows, hl, ref, got) in enumerate(COPIES[:step]):
        x = 60 + i * 375
        bottom = table(d, x, 225, rows, hl, w=330, title=name)
        ok = ref == got
        d.text((x, bottom + 22), f"reference {ref}  ·  agent {got}", font=font(20), fill=INK)
        d.text((x + 330, bottom + 34), "✓" if ok else "✗", font=font(34, bold=True), fill=GREEN if ok else RED, anchor="rm")
    if step > len(COPIES):
        d.rounded_rectangle([300, 535, 900, 605], radius=12, fill="#fdecec", outline=RED, width=3)
        d.text((W // 2, 570), "✗  Strict reward 0: bug caught", font=font(30, bold=True), fill=RED, anchor="mm")
    footer(d)
    return im


BARS = [("Buggy queries paid in full", 29.5, 16.8), ("Reward hacks paid", 54.1, 1.9)]


def results(t):
    im, d = canvas()
    d.text((60, 45), "On 1,302 audit questions", font=font(32, bold=True), fill=INK)
    d.rectangle([60, 110, 84, 130], fill=GREY)
    d.text((94, 120), "single-DB reward", font=font(20), fill=INK, anchor="lm")
    d.rectangle([330, 110, 354, 130], fill=BLUE)
    d.text((364, 120), "counterfactual reward", font=font(20), fill=INK, anchor="lm")
    scale = 13.0  # px per percentage point
    for i, (label, a, b) in enumerate(BARS):
        y = 175 + i * 165
        d.text((60, y), label, font=font(24, bold=True), fill=INK)
        for j, (v, c) in enumerate(((a, GREY), (b, BLUE))):
            by = y + 42 + j * 46
            d.rectangle([60, by, 60 + max(2, v * t * scale), by + 36], fill=c)
            d.text((70 + max(2, v * t * scale), by + 18), f"{v * t:.1f}%", font=font(22, bold=True), fill=INK, anchor="lm")
    if t >= 1:
        d.text((60, 525), "0 of 2,847 correct queries rejected", font=font(28, bold=True), fill=GREEN)
        d.text((60, 572), "In 3-seed GRPO training it did not raise in-domain accuracy; one seed flips the result.",
               font=font(20), fill=MUTED)
    footer(d)
    return im


def end_card():
    im, d = canvas()
    d.text((W // 2, 170), "Pay a query only if it holds up", font=font(44, bold=True), fill=INK, anchor="mm")
    d.text((W // 2, 230), "on databases the agent never sees.", font=font(44, bold=True), fill=BLUE, anchor="mm")
    rows = [("Paper", "arxiv.org/abs/2611.34363"),
            ("Code", "github.com/RishiiGamer2201/counterfactual-sql-rewards"),
            ("Demo, models, data", "huggingface.co/counterfactual-sql")]
    for i, (k, v) in enumerate(rows):
        y = 340 + i * 60
        d.text((300, y), k, font=font(24, bold=True), fill=MUTED, anchor="rm")
        d.text((330, y), v, font=font(24, mono=True), fill=INK, anchor="lm")
    footer(d)
    return im


def frames():
    yield title_card(), 2600
    for s, ms in ((0, 1400), (1, 700), (2, 700), (3, 3200)):
        yield single_db(s), ms
    for s, ms in ((1, 900), (2, 900), (3, 900), (4, 3200)):
        yield counterfactual(s), ms
    n = 14
    for k in range(1, n + 1):
        yield results(k / n), 3400 if k == n else 70
    yield end_card(), 4000


def main():
    out = Path(sys.argv[1])
    prev = Path(sys.argv[2]) if len(sys.argv) > 2 else None
    ims, durs = [], []
    for i, (im, ms) in enumerate(frames()):
        if prev:
            prev.mkdir(parents=True, exist_ok=True)
            im.save(prev / f"f{i:02d}.png")
        ims.append(im.convert("P", palette=Image.ADAPTIVE, colors=64, dither=Image.Dither.NONE))
        durs.append(ms)
    ims[0].save(out, save_all=True, append_images=ims[1:], duration=durs, loop=0, optimize=True)
    print(out, len(ims), "frames", round(sum(durs) / 1000, 1), "s", out.stat().st_size // 1024, "KB")


if __name__ == "__main__":
    main()
